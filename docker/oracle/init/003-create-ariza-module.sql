WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES
     WHERE OWNER = 'STOKTAKIP' AND TABLE_NAME = 'ARIZA';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STOKTAKIP.ARIZA (
                GUID VARCHAR2(128) NOT NULL,
                ENVANTER_GUID VARCHAR2(128) NOT NULL,
                ARIZA_TARIHI TIMESTAMP NOT NULL,
                ARIZA_ACIKLAMASI VARCHAR2(2000) NOT NULL,
                BILDIRIM_YAPAN_PERSONEL_KODU VARCHAR2(100),
                SON_DURUM VARCHAR2(40) NOT NULL,
                KAPANDI_MI BOOLEAN DEFAULT FALSE NOT NULL,
                KAPANIS_TARIHI TIMESTAMP,
                ACIKLAMA VARCHAR2(2000),
                DURUM VARCHAR2(32) DEFAULT 'AKTIF' NOT NULL,
                K_TARIH TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                SILINDI BOOLEAN DEFAULT FALSE NOT NULL,
                CONSTRAINT PK_ARIZA PRIMARY KEY (GUID),
                CONSTRAINT FK_ARIZA_ENVANTER FOREIGN KEY (ENVANTER_GUID)
                    REFERENCES STOKTAKIP.ENVANTER (GUID)
            )
        ]';
        EXECUTE IMMEDIATE 'CREATE INDEX STOKTAKIP.IX_ARIZA_ENV_TARIH ON STOKTAKIP.ARIZA (ENVANTER_GUID, ARIZA_TARIHI)';
        EXECUTE IMMEDIATE 'CREATE INDEX STOKTAKIP.IX_ARIZA_LISTE ON STOKTAKIP.ARIZA (KAPANDI_MI, SON_DURUM, ARIZA_TARIHI)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM ALL_TABLES
     WHERE OWNER = 'STOKTAKIP' AND TABLE_NAME = 'ARIZA_DURUMU';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STOKTAKIP.ARIZA_DURUMU (
                GUID VARCHAR2(128) NOT NULL,
                ARIZA_GUID VARCHAR2(128) NOT NULL,
                DURUM_TIPI VARCHAR2(40) NOT NULL,
                DURUM_TARIHI TIMESTAMP NOT NULL,
                ACIKLAMA VARCHAR2(2000),
                SERVIS_ADI VARCHAR2(255),
                SERVIS_REFERANS_NO VARCHAR2(100),
                KARGO_FIRMASI VARCHAR2(255),
                KARGO_TAKIP_NO VARCHAR2(100),
                TAMIR_SONUCU VARCHAR2(40),
                TAMIR_ACIKLAMASI VARCHAR2(2000),
                MASRAF NUMBER(19,2),
                PARA_BIRIMI VARCHAR2(3),
                DURUM VARCHAR2(32) DEFAULT 'AKTIF' NOT NULL,
                K_TARIH TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                SILINDI BOOLEAN DEFAULT FALSE NOT NULL,
                CONSTRAINT PK_ARIZA_DURUMU PRIMARY KEY (GUID),
                CONSTRAINT FK_ARIZA_DURUMU_ARIZA FOREIGN KEY (ARIZA_GUID)
                    REFERENCES STOKTAKIP.ARIZA (GUID),
                CONSTRAINT CK_ARIZA_MASRAF CHECK (MASRAF IS NULL OR MASRAF >= 0)
            )
        ]';
        EXECUTE IMMEDIATE 'CREATE INDEX STOKTAKIP.IX_ARIZA_DURUMU_TARIH ON STOKTAKIP.ARIZA_DURUMU (ARIZA_GUID, DURUM_TARIHI)';
    END IF;
END;
